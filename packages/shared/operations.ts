export function operationPath<T extends OperationId>(
  operationId: T,
  params: Record<string, string> = {},
) {
  let path: string = operations[operationId].pathTemplate;
  for (const [key, value] of Object.entries(params))
    path = path.replace(`:${key}`, encodeURIComponent(value));
  return path;
}

