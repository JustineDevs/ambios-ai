/**
 * Canonical HTTP operation registry.
 *
 * Raw AmbiOS route templates belong here (and only here). Consumers use an
 * operation ID plus path() so changing a route cannot silently leave a stale
 * caller behind. Schema names are stable contract identifiers; the runtime
 * adapters own the actual validator implementation.
 */
export type RuntimeOwner = "core-api" | "connector-execution" | "mcp-oauth";
export type Exposure = "public" | "protected";
export type Requirement = "none" | "required" | "optional";
export type Availability =
  | "live"
  | "preview"
  | "sandbox"
  | "not-configured"
  | "unverified"
  | "unsupported"
  | "deprecated";
export type OperationCategory =
  | "health"
  | "identity"
  | "auth"
  | "workspace"
  | "readiness"
  | "incidents"
  | "actions"
  | "approvals"
  | "guardrails"
  | "integrations"
  | "providers"
  | "resourceMappings"
  | "canvas"
  | "runs"
  | "console"
  | "audit"
  | "docs"
  | "artifacts"
  | "budget"
  | "sync"
  | "logs"
  | "deployment"
  | "hotfixes"
  | "webhooks"
  | "mcp"
  | "mcpOAuth"
  | "apiKeys"
  | "systems"
  | "services";

export type OperationDefinition = {
  readonly operationId: string;
  readonly category: OperationCategory;
  readonly method: "GET" | "POST" | "PUT" | "PATCH" | "DELETE" | "ALL";
  readonly pathTemplate: string;
  readonly runtimeOwner: RuntimeOwner;
  readonly publicOrProtected: Exposure;
  readonly authenticationRequirement: Requirement;
  readonly organizationScopeRequirement: boolean;
  readonly workspaceScopeRequirement: boolean;
  readonly roleRequirement: string | null;
  readonly capabilityRequirement: string | null;
  readonly requestSchema: string | null;
  readonly responseSchema: string;
  readonly problemSchemas: readonly string[];
  readonly paginationSchema: string | null;
  readonly idempotencyRequirement: "none" | "recommended" | "required";
  readonly rateLimitCategory: "none" | "read" | "write" | "auth" | "webhook" | "provider";
  readonly auditRequirement: "none" | "optional" | "required";
  readonly queueRequirement: "none" | "producer" | "consumer";
  readonly providerRequirement: string | null;
  readonly verificationRequirement: "none" | "independent";
  readonly supportedStatus: Availability;
  readonly frontendAvailability: boolean;
  readonly webMcpAvailability: boolean;
  readonly remoteMcpAvailability: boolean;
  readonly documentationSummary: string;
  readonly deprecationStatus: "current" | "deprecated";
  readonly replacementOperationId: string | null;
  readonly sunsetDate: string | null;
  readonly migrationOwner: string | null;
  readonly clientMigrationStatus: "canonical" | "migrating" | "legacy";
  readonly examples: readonly string[];
};

type OperationInput = Omit<
  OperationDefinition,
  | "category"
  | "publicOrProtected"
  | "authenticationRequirement"
  | "organizationScopeRequirement"
  | "workspaceScopeRequirement"
  | "roleRequirement"
  | "capabilityRequirement"
  | "requestSchema"
  | "problemSchemas"
  | "paginationSchema"
  | "idempotencyRequirement"
  | "rateLimitCategory"
  | "auditRequirement"
  | "queueRequirement"
  | "providerRequirement"
  | "verificationRequirement"
  | "supportedStatus"
  | "frontendAvailability"
  | "webMcpAvailability"
  | "remoteMcpAvailability"
  | "deprecationStatus"
  | "replacementOperationId"
  | "sunsetDate"
  | "migrationOwner"
  | "clientMigrationStatus"
  | "examples"
> &
  Partial<
    Omit<
      OperationDefinition,
      | "operationId"
      | "method"
      | "pathTemplate"
      | "runtimeOwner"
      | "responseSchema"
      | "documentationSummary"
    >
  > &
  Pick<
    OperationDefinition,
    | "operationId"
    | "method"
    | "pathTemplate"
    | "runtimeOwner"
    | "responseSchema"
    | "documentationSummary"
  >;

const defaults: Omit<OperationDefinition, keyof OperationInput> = {
  category: "services",
  publicOrProtected: "protected",
  authenticationRequirement: "required",
  organizationScopeRequirement: true,
  workspaceScopeRequirement: true,
  roleRequirement: null,
  capabilityRequirement: null,
  requestSchema: null,
  problemSchemas: ["Problem"],
  paginationSchema: null,
  idempotencyRequirement: "none",
  rateLimitCategory: "read",
  auditRequirement: "optional",
  queueRequirement: "none",
  providerRequirement: null,
  verificationRequirement: "none",
  supportedStatus: "live",
  frontendAvailability: true,
  webMcpAvailability: false,
  remoteMcpAvailability: false,
  deprecationStatus: "current",
  replacementOperationId: null,
  sunsetDate: null,
  migrationOwner: null,
  clientMigrationStatus: "canonical",
  examples: [],
};

const defineOperation = <const T extends OperationInput>(input: T): OperationDefinition =>
  ({ ...defaults, ...input }) as OperationDefinition;

const defineLegacyOperation = <const T extends OperationInput>(input: T): OperationDefinition =>
  defineOperation({
    ...input,
    deprecationStatus: "deprecated",
    supportedStatus: "deprecated",
    clientMigrationStatus: "legacy",
    sunsetDate: "2026-12-31",
    migrationOwner: "platform",
  });

